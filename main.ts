input.onButtonPressed(Button.A, function () {
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo7, 45, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo5, 45, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo10, 45, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo12, 135, 64)
    basic.pause(200)
})
input.onButtonPressed(Button.B, function () {
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo7, 180, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo6, 180, 64)
    basic.pause(500)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo7, 90, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo6, 100, 64)
    basic.pause(500)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo5, 0, 64)
    basic.pause(200)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo5, 90, 64)
    basic.pause(200)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo5, 0, 64)
    basic.pause(200)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo5, 90, 64)
    basic.pause(200)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo7, 180, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo6, 180, 64)
})
input.onLogoEvent(TouchButtonEvent.Pressed, function () {
    basic.pause(2000)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo13, 180, 64)
    PCA9685.setServoPosition(PCA9685.ServoNum.Servo4, 0, 64)
})
PCA9685.reset(PCA9685.chipAddress("0x40"))
